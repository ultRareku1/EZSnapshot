import Foundation

/// Supported interface languages. System mode follows the first supported preferred language.
enum AppLanguage: String, CaseIterable, Identifiable, Codable, Sendable {
    case system
    case enUS = "en-US"
    case zhCN = "zh-CN"
    case zhTW = "zh-TW"
    case jaJP = "ja-JP"
    case koKR = "ko-KR"
    case frFR = "fr-FR"
    case deDE = "de-DE"
    case esES = "es-ES"

    var id: String { rawValue }

    var flag: String {
        switch self {
        case .system: "🌐"
        case .enUS: "🇺🇸"
        case .zhCN: "🇨🇳"
        case .zhTW: "🇹🇼"
        case .jaJP: "🇯🇵"
        case .koKR: "🇰🇷"
        case .frFR: "🇫🇷"
        case .deDE: "🇩🇪"
        case .esES: "🇪🇸"
        }
    }

    var nativeName: String {
        switch self {
        case .system: "System default"
        case .enUS: "English (US)"
        case .zhCN: "简体中文（中国）"
        case .zhTW: "繁體中文（台灣）"
        case .jaJP: "日本語（日本）"
        case .koKR: "한국어 (대한민국)"
        case .frFR: "Français (France)"
        case .deDE: "Deutsch (Deutschland)"
        case .esES: "Español (España)"
        }
    }

    var localeIdentifier: String {
        switch resolved {
        case .system, .enUS: "en_US"
        case .zhCN: "zh_Hans_CN"
        case .zhTW: "zh_Hant_TW"
        case .jaJP: "ja_JP"
        case .koKR: "ko_KR"
        case .frFR: "fr_FR"
        case .deDE: "de_DE"
        case .esES: "es_ES"
        }
    }

    var resolved: AppLanguage {
        guard self == .system else { return self }
        for identifier in Locale.preferredLanguages {
            if let language = Self.matchingLanguage(identifier) { return language }
        }
        return .enUS
    }

    private static func matchingLanguage(_ identifier: String) -> AppLanguage? {
        let parts = identifier.replacingOccurrences(of: "_", with: "-")
            .lowercased().split(separator: "-").map(String.init)
        guard let language = parts.first else { return nil }
        switch language {
        case "en": return .enUS
        case "zh":
            // The explicit script takes priority over the country. For region-only
            // preferences, Taiwan, Hong Kong, and Macau use Traditional Chinese.
            if parts.contains("hant") { return .zhTW }
            if parts.contains("hans") { return .zhCN }
            return parts.contains(where: { ["tw", "hk", "mo"].contains($0) }) ? .zhTW : .zhCN
        case "ja": return .jaJP
        case "ko": return .koKR
        case "fr": return .frFR
        case "de": return .deDE
        case "es": return .esES
        default: return nil
        }
    }

    func string(_ key: L10nKey) -> String {
        Self.translations[resolved]?[key] ?? Self.translations[.enUS]?[key] ?? key.rawValue
    }

